raw AS (
  SELECT
    DATE_FORMAT(CAST(AT_TIMEZONE(t.time_of_event, 'Asia/Kolkata') AS TIMESTAMP), '%Y-%m') AS month_key,
    t.tin,
    COALESCE(t.seat_count, 0) AS seat_count,
    COALESCE(t.ticket_fare, 0) AS ticket_fare,
    t.operator_id,
    t.route_id,
    t.source_location_id,
    t.destination_location_id,
    DATE_FORMAT(CAST(AT_TIMEZONE(t.date_of_journey, 'Asia/Kolkata') AS TIMESTAMP), '%Y') AS doj_year,
    day_of_week(CAST(AT_TIMEZONE(t.date_of_journey, 'Asia/Kolkata') AS DATE)) AS doj_dow,
    DATE_DIFF(
      'minute',
      CAST(AT_TIMEZONE(COALESCE(t.boarding_time, t.date_of_journey), 'Asia/Kolkata') AS TIMESTAMP),
      t.arrival_time
    ) AS travel_minutes,
    CARDINALITY(t.travellers_gender) AS pax_n,
    UPPER(TRIM(CAST(element_at(t.travellers_gender, 1) AS VARCHAR))) AS g1,
    UPPER(TRIM(CAST(element_at(t.travellers_gender, 2) AS VARCHAR))) AS g2,
    CASE
      WHEN t.sales_channel = 'RB:MOBILEWEB#droidapp' THEN 'Android'
      WHEN t.sales_channel = 'RB:MOBILEWEB#iosapp' THEN 'iOS'
      ELSE 'Others'
    END AS channel_cut,
    EXTRACT(HOUR FROM AT_TIMEZONE(t.time_of_event, 'Asia/Kolkata')) AS issue_hour,
    DATE_DIFF(
      'day',
      CAST(AT_TIMEZONE(t.time_of_event, 'Asia/Kolkata') AS DATE),
      CAST(AT_TIMEZONE(t.date_of_journey, 'Asia/Kolkata') AS DATE)
    ) AS dbd_days,
    CASE
      WHEN UPPER(COALESCE(t.user_type, '')) = 'NEW' THEN 'NEW'
      WHEN UPPER(COALESCE(t.user_type, '')) IN ('RETURNING', 'EXISTING', 'OLD') THEN 'RETURNING'
      WHEN UPPER(COALESCE(t.user_type, '')) = 'GUEST' THEN 'GUEST'
      ELSE 'OTHER'
    END AS user_type_cut,
    DATE_DIFF(
      'minute',
      t.time_of_event,
      COALESCE(t.date_of_journey, t.boarding_time)
    ) AS minutes_before_journey
  FROM transaction.bus_ticket_events t
  WHERE t.country_code = 'IND'
    AND t.event_type = 101
    AND t.event_class = 2
    AND t.tin IS NOT NULL
    AND t.time_of_event >= TIMESTAMP '2024-12-31 18:30:00'
    AND t.time_of_event < TIMESTAMP '2026-09-30 18:30:00'
    AND t.sales_channel IN (
      'RB:MOBILEWEB#droidapp',
      'RB:MOBILEWEB#iosapp',
      'MOBILEWEB',
      'WEBDIRECT'
    )
),
base AS (
  SELECT
    r.month_key,
    r.tin,
    r.seat_count,
    r.ticket_fare,
    r.channel_cut,
    r.user_type_cut,
    CASE
      WHEN r.dbd_days = 0 AND r.issue_hour BETWEEN 17 AND 23 THEN 'LMB'
      ELSE 'Non_LMB'
    END AS segment,
    COALESCE(src_tier.tier, 'Tier 3') || ' -> ' || COALESCE(dst_tier.tier, 'Tier 3') AS sd_tier,
    CASE
      WHEN r.seat_count <= 1 THEN '1'
      WHEN r.seat_count = 2 THEN '2'
      ELSE 'Group'
    END AS booking,
    CASE
      WHEN r.seat_count <= 0 THEN 'Unknown'
      WHEN r.ticket_fare / r.seat_count < 500 THEN '<500'
      WHEN r.ticket_fare / r.seat_count < 800 THEN '500-799'
      WHEN r.ticket_fare / r.seat_count < 1200 THEN '800-1199'
      WHEN r.ticket_fare / r.seat_count < 1800 THEN '1200-1799'
      ELSE '1800+'
    END AS asp_bucket,
    COALESCE(bo.region, 'Unknown') AS region,
    CASE
      WHEN bo.is_rtc = 'RTC' THEN 'RTC'
      WHEN bo.is_rtc = 'Private' THEN 'Private'
      ELSE 'Unknown'
    END AS operator_type,
    CASE
      WHEN r200.src IS NOT NULL THEN 'Top 200'
      WHEN r500.src IS NOT NULL THEN '201-500'
      ELSE 'Rest'
    END AS route_band,
    CASE
      WHEN r.minutes_before_journey IS NULL OR r.minutes_before_journey < 0 THEN 'Unknown'
      WHEN r.minutes_before_journey < 60 THEN '0-1'
      WHEN r.minutes_before_journey < 120 THEN '1-2'
      WHEN r.minutes_before_journey < 240 THEN '2-4'
      WHEN r.minutes_before_journey < 360 THEN '4-6'
      ELSE '>6'
    END AS doj_doi,
    CASE
      WHEN sr.src_id IS NOT NULL THEN 'Short'
      ELSE 'Long'
    END AS distance_band,
    CASE
      WHEN r.travel_minutes IS NULL OR r.travel_minutes < 0 OR r.travel_minutes >= 4320 THEN 'Unknown'
      WHEN r.travel_minutes < 180 THEN '<3h'
      WHEN r.travel_minutes < 360 THEN '3-6h'
      WHEN r.travel_minutes < 540 THEN '6-9h'
      WHEN r.travel_minutes < 720 THEN '9-12h'
      ELSE '12h+'
    END AS travel_duration,
    CASE
      WHEN r.doj_dow IN (5, 6, 7) THEN 'Weekend'
      WHEN r.doj_dow IN (1, 2, 3, 4) THEN 'Weekday'
      ELSE 'Unknown'
    END AS dow_cut,
    CASE
      WHEN rp.route_id IS NULL THEN 'Unknown'
      WHEN rp.is_via = 0 THEN 'Through'
      ELSE 'Via'
    END AS route_path_cut,
    CASE
      WHEN r.pax_n = 1 AND r.g1 IN ('MALE', 'M') THEN 'm'
      WHEN r.pax_n = 1 AND r.g1 IN ('FEMALE', 'F') THEN 'f'
      WHEN r.pax_n = 2 AND r.g1 IN ('MALE', 'M') AND r.g2 IN ('MALE', 'M') THEN 'mm'
      WHEN r.pax_n = 2 AND r.g1 IN ('FEMALE', 'F') AND r.g2 IN ('FEMALE', 'F') THEN 'ff'
      WHEN r.pax_n = 2 AND r.g1 IN ('MALE', 'M') AND r.g2 IN ('FEMALE', 'F') THEN 'mf'
      WHEN r.pax_n = 2 AND r.g1 IN ('FEMALE', 'F') AND r.g2 IN ('MALE', 'M') THEN 'fm'
      ELSE 'Other'
    END AS passenger_mix
  FROM raw r
  LEFT JOIN lis.bo_mappings bo ON bo.vendor_id = r.operator_id
  LEFT JOIN top200 r200
    ON r.source_location_id = r200.src AND r.destination_location_id = r200.dest
  LEFT JOIN top500 r500
    ON r.source_location_id = r500.src AND r.destination_location_id = r500.dest
  LEFT JOIN city_tier_map src_tier ON src_tier.loc_id = r.source_location_id
  LEFT JOIN city_tier_map dst_tier ON dst_tier.loc_id = r.destination_location_id
  LEFT JOIN short_routes sr
    ON r.source_location_id = sr.src_id
   AND r.destination_location_id = sr.dest_id
   AND sr.cohort = r.doj_year
  LEFT JOIN route_path rp ON rp.route_id = r.route_id
)
SELECT
  month_key,
  CASE
    WHEN GROUPING(booking) = 0 THEN 'Booking'
    WHEN GROUPING(asp_bucket) = 0 THEN 'ASP'
    WHEN GROUPING(region) = 0 THEN 'Region'
    WHEN GROUPING(route_band) = 0 THEN 'Route'
    WHEN GROUPING(operator_type) = 0 THEN 'Operator'
    WHEN GROUPING(doj_doi) = 0 THEN 'DOJ-DOI'
    WHEN GROUPING(sd_tier) = 0 THEN 'SD Tier'
    WHEN GROUPING(distance_band) = 0 THEN 'Distance'
    WHEN GROUPING(travel_duration) = 0 THEN 'Travel Duration'
    WHEN GROUPING(dow_cut) = 0 THEN 'Week Part'
    WHEN GROUPING(route_path_cut) = 0 THEN 'Route Path'
    WHEN GROUPING(passenger_mix) = 0 THEN 'Passenger Mix'
  END AS cut,
  COALESCE(
    booking, asp_bucket, region, route_band, operator_type, doj_doi, sd_tier,
    distance_band, travel_duration, dow_cut, route_path_cut, passenger_mix
  ) AS cut_value,
  segment,
  channel_cut,
  user_type_cut,
  COUNT(DISTINCT tin) AS orders,
  SUM(seat_count) AS seats,
  SUM(ticket_fare) AS fare
FROM base
GROUP BY GROUPING SETS (
  (month_key, segment, channel_cut, user_type_cut, booking),
  (month_key, segment, channel_cut, user_type_cut, asp_bucket),
  (month_key, segment, channel_cut, user_type_cut, region),
  (month_key, segment, channel_cut, user_type_cut, route_band),
  (month_key, segment, channel_cut, user_type_cut, operator_type),
  (month_key, segment, channel_cut, user_type_cut, doj_doi),
  (month_key, segment, channel_cut, user_type_cut, sd_tier),
  (month_key, segment, channel_cut, user_type_cut, distance_band),
  (month_key, segment, channel_cut, user_type_cut, travel_duration),
  (month_key, segment, channel_cut, user_type_cut, dow_cut),
  (month_key, segment, channel_cut, user_type_cut, route_path_cut),
  (month_key, segment, channel_cut, user_type_cut, passenger_mix)
)
