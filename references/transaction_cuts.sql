-- Optimised LMB transaction cuts. India. IST Jan 2025 through Sep 2026.
-- One scan of transaction.bus_ticket_events. search_route_details is not read.
--
-- LMB: the ticket is issued 17:00-23:59 IST and the journey date is that same IST date.
-- Non LMB: every other confirmed ticket in the window.
-- Channel: RB:MOBILEWEB#droidapp Android, RB:MOBILEWEB#iosapp iOS, MOBILEWEB + WEBDIRECT Others.
-- Route rank: source x destination by distinct TINs over this same window. Top 500 includes Top 200.
-- ASP bucket: ticket_fare / seat_count.
-- Region and Private/RTC: lis.bo_mappings on operator_id.
-- DOJ-DOI: minutes from issue (time_of_event) to journey start (date_of_journey, both UTC).
--   0-1 = booked under 1 hour before the journey, 1-2 = 1 to under 2 hours, then 2-4, 4-6, >6.
-- Channel and usertype sit on every dimension.
-- Usertype: ticket user_type (NEW / RETURNING / GUEST).
-- SD tier: Mehar city map on source and destination. Label is 'Tier 1 -> Pilgrim'.
--   Cities not in the Tier 1 / Tier 2 / Pilgrim / Leisure list are Tier 3.
-- Distance: Short when the SD is in lis.short_route_sds for the journey year (2025 or 2026). Else Long.
-- Travel duration: minutes from boarding (UTC, shown in IST) to arrival_time (local).
--   Buckets: <3h, 3-6h, 6-9h, 9-12h, 12h+. Unknown when missing, negative, or 72h or more.
-- Week part: Weekend is Friday, Saturday, Sunday on the IST journey date. Weekday is Monday-Thursday.
-- Route path: Through when lis.routes.is_via = 0. Via when is_via is anything else. Unknown when the route is missing.
-- Passenger mix from travellers_gender, in seat order: m, f, mm, ff, mf, fm. Anything else is Other.

